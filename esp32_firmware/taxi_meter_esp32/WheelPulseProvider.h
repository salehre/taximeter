#pragma once

// اینترفیس یک حسگر پالسی روی چرخ یا میل‌گاردان (مثلاً حسگر هال یا ریدسوییچ
// مغناطیسی). این یک منبع مسافت *مکمل* GPS است، نه جایگزین آن:
//
//   - GPS می‌تواند در تونل، بین ساختمان‌های بلند، یا به‌خاطر نویز/چندمسیری
//     (multipath) دچار خطا یا قطعی شود.
//   - حسگر چرخ همیشه دقیقاً مسافت واقعی طی‌شده‌ی چرخ را می‌شمارد، مستقل از
//     شرایط جوی/شهری، و نسبت به GPS خیلی سخت‌تر قابل دستکاری/فریب دادن است.
//
// دقیقاً همین رویکرد (اتصال به گیربکس/چرخ به‌جای تکیه‌ی صرف به GPS) پایه‌ی
// استانداردهای رسمی تاکسی‌متر در اروپا (OIML R21 / MID) و آمریکا (NTEP) است.
//
// TaxiMeterSystem این حسگر را کاملاً اختیاری در نظر می‌گیرد: اگر isInstalled()
// false برگرداند (یا اصلاً وصل نشده باشد)، سیستم دقیقاً مثل قبل فقط از GPS
// استفاده می‌کند -- یعنی افزودن این فیچر هیچ رفتار قبلی را نمی‌شکند.
//
// - روی دسکتاپ: SimulatedWheelPulseProvider (پالس جعلی هم‌زمان با GPS شبیه‌سازی‌شده)
// - روی ESP32: Esp32WheelPulseProvider (شمارش پالس واقعی با وقفه‌ی سخت‌افزاری)
class WheelPulseProvider {
public:
    // true یعنی این حسگر واقعاً روی دستگاه سیم‌کشی/فعال شده است.
    virtual bool isInstalled() const = 0;

    // مسافت طی‌شده (متر) از آخرین باری که این تابع صدا زده شده؛ شمارنده‌ی
    // داخلی صفر می‌شود. باید هر بار هم‌زمان با هر خوانش GPS صدا زده شود
    // (TaxiMeterSystem این کار را خودش انجام می‌دهد).
    virtual double consumeDistanceMeters() = 0;

    virtual ~WheelPulseProvider() {}
};
